#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, "..");
const coreTypes = readFileSync(resolve(packageRoot, "../core/dist/index.d.ts"), "utf8");
const scriptTypes = readFileSync(resolve(packageRoot, "../script/dist/index.d.ts"), "utf8");

const output = `// Generated by scripts/generate-types.mjs. Do not edit.
export const CORE_TYPES = ${JSON.stringify(coreTypes)};
export const SCRIPT_TYPES = ${JSON.stringify(scriptTypes)};
`;

writeFileSync(resolve(packageRoot, "src/types.generated.ts"), output);
console.log("Generated WickScript editor type declarations");
